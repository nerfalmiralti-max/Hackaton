import { createHash } from "node:crypto";
import { mkdir, open, readFile, realpath, rename, stat, unlink, writeFile } from "node:fs/promises";
import { resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const directory = resolve(root, ".data/knowledge");
const manifestPath = resolve(directory, "index-manifest.json");
const args = process.argv.slice(2);
if (args.includes("--help")) {
  console.log("node scripts/index-knowledge.mjs --dry-run\nnode scripts/index-knowledge.mjs --upload\nDry-run is the default and makes no OpenAI calls. --upload explicitly sends extracted textbook text to OpenAI and may incur charges. Reads .env.local; never prints the key.");
  process.exit(0);
}
if (args.some((arg) => !["--dry-run", "--upload"].includes(arg)) || (args.includes("--upload") && args.includes("--dry-run"))) {
  throw new Error("Use --dry-run or --upload, not both");
}
async function save(manifest) {
  const temporary = `${manifestPath}.tmp`;
  await writeFile(temporary, `${JSON.stringify(manifest, null, 2)}\n`, { mode: 0o600 });
  await rename(temporary, manifestPath);
}
async function readManifest() {
  try {
    const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
    if (manifest.version !== 1 || !Array.isArray(manifest.files)) throw new Error("Invalid index manifest");
    return manifest;
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
    return { version: 1, vectorStoreId: null, files: [] };
  }
}
async function main() {
  const catalog = JSON.parse(await readFile(resolve(root, "knowledge/catalog.json"), "utf8"));
  if (!Array.isArray(catalog)) throw new Error("Invalid catalog");
  const prepared = [];
  for (const book of catalog) {
    if (!/^[a-z0-9-]+$/.test(book.id) || book.textPath !== `.data/knowledge/${book.id}.txt`) throw new Error("Invalid catalog text path");
    if (book.extraction?.status !== "extracted" || !book.extraction.pagesWithText) {
      console.log(`Skip ${book.id}: no extracted text`);
      continue;
    }
    let path;
    try { path = await realpath(resolve(root, book.textPath)); }
    catch (error) {
      if (error.code !== "ENOENT") throw error;
      console.log(`Skip ${book.id}: local text missing`);
      continue;
    }
    if (!path.startsWith(directory + sep)) throw new Error("Text path escapes private knowledge directory");
    const info = await stat(path);
    if (!info.isFile() || info.size > 32 * 1024 * 1024) throw new Error("Invalid or oversized extracted text");
    const bytes = await readFile(path);
    const text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
    if (!/[\p{L}\p{N}]{2,}/u.test(text)) continue;
    const filename = `${book.id}-grade-${book.grade}-${book.language}.txt`;
    // Page labels are input provenance, not source claims generated by a model.
    const indexedText = text.split("\f").map((page, i) => `[PDF page ${i + 1}]\n${page}`).join("\n\n");
    prepared.push({ book, filename, bytes: Buffer.from(indexedText, "utf8"), sha256: createHash("sha256").update(bytes).digest("hex") });
  }
  if (!args.includes("--upload")) {
    for (const file of prepared) console.log(`Dry-run: ${file.filename}, ${file.book.pages} pages, ${file.bytes.length} upload bytes`);
    console.log(`${prepared.length} files ready. No OpenAI calls; no index manifest changed.`);
    return;
  }
  try { process.loadEnvFile(resolve(root, ".env.local")); }
  catch (error) { if (error.code !== "ENOENT") throw error; }
  if (!process.env.OPENAI_API_KEY?.trim()) throw new Error("OPENAI_API_KEY missing. Configure .env.local and explicitly run --upload when authorized.");
  if (!prepared.length) throw new Error("No extracted books to upload");
  await mkdir(directory, { recursive: true });
  const lockPath = resolve(directory, "index.lock");
  const lock = await open(lockPath, "wx", 0o600);
  try {
    const { default: OpenAI, toFile } = await import("openai");
    const client = new OpenAI({ apiKey: process.env.OPENAI_API_KEY.trim(), maxRetries: 0, timeout: 90_000 });
    const manifest = await readManifest();
    const configuredId = process.env.OPENAI_VECTOR_STORE_ID?.trim();
    if (configuredId && manifest.vectorStoreId && configuredId !== manifest.vectorStoreId) throw new Error("Configured store differs from saved admin store. Resolve manifest configuration before uploading.");
    let storeId = configuredId || manifest.vectorStoreId;
    if (storeId) {
      const store = await client.vectorStores.retrieve(storeId);
      if (store.status === "expired") throw new Error("Saved admin vector store has expired");
    } else {
      const store = await client.vectorStores.create({ name: "Local textbook collection (administrator provided; no official NIS integration)" });
      storeId = store.id;
    }
    manifest.vectorStoreId = storeId;
    await save(manifest);
    for (const file of prepared) {
      let record = manifest.files.find((item) => item.id === file.book.id && item.sha256 === file.sha256);
      if (!record) {
        record = { id: file.book.id, sha256: file.sha256, name: file.filename, status: "pending" };
        manifest.files.push(record);
        await save(manifest);
      }
      const signal = AbortSignal.timeout(10 * 60 * 1000);
      try {
        let association;
        if (record.fileId) {
          try { association = await client.vectorStores.files.retrieve(record.fileId, { vector_store_id: storeId }, { signal }); }
          catch (error) { if (error.status !== 404) throw error; }
        }
        if (association?.status === "completed") {
          record.status = "completed";
          await save(manifest);
          console.log(`Reuse indexed ${file.filename}`);
          continue;
        }
        if (!record.fileId) {
          const uploaded = await client.files.create({ file: await toFile(file.bytes, file.filename, { type: "text/plain" }), purpose: "assistants" }, { signal });
          record.fileId = uploaded.id;
          record.status = "uploaded";
          await save(manifest);
        }
        if (association?.status === "failed" || association?.status === "cancelled") {
          await client.vectorStores.files.delete(record.fileId, { vector_store_id: storeId }, { signal });
          association = undefined;
        }
        const indexed = association
          ? await client.vectorStores.files.poll(storeId, record.fileId, { signal, pollIntervalMs: 1000 })
          : await client.vectorStores.files.createAndPoll(storeId, { file_id: record.fileId, attributes: { catalog_id: file.book.id, grade: file.book.grade, subject: file.book.subject, language: file.book.language } }, { signal, pollIntervalMs: 1000 });
        record.status = indexed.status;
        record.indexedAt = new Date().toISOString();
        await save(manifest);
        if (indexed.status !== "completed") throw new Error(`Indexing did not complete for ${file.filename}`);
        console.log(`Indexed ${file.filename}`);
      } catch (error) {
        record.status = "failed";
        await save(manifest);
        throw error;
      }
    }
    console.log(`Admin vector store: ${storeId}\nSet OPENAI_VECTOR_STORE_ID=${storeId} in .env.local and restart the server.`);
  } finally {
    await lock.close();
    await unlink(lockPath);
  }
}
main().catch((error) => {
  // Upstream response bodies are intentionally not logged with credentials/configuration.
  console.error(error.status ? `OpenAI request failed (HTTP ${error.status}). Inspect the private index manifest and retry.` : error instanceof Error ? error.message : "Indexing failed");
  process.exitCode = 1;
});
